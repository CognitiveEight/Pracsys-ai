def format_targeted_acts_for_prompt(
    acts: Optional[List[str]] = None,
    bullet: str = "- ",
) -> str:
    """Render the targeted-acts list as a bullet block for inclusion in a prompt.

    Returns one act per line, prefixed with ``bullet``. Use this in the
    applicable_laws Gemini prompt so the model sees the canonical universe of
    statutes the product wants to target.
    """
    items = acts if acts is not None else TARGETED_INDIAN_ACTS
    return "\n".join(f"{bullet}{name}" for name in items)


